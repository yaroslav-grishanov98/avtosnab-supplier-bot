_COMPILED = [(re.compile(pattern), subgroup, leaf) for pattern, subgroup, leaf in RULES]
_FOOD_ROOT_KEY = "продуктыпитания"


def _key(value):
    return re.sub(r"[^a-z0-9%а-я]", "", (value or "").lower().replace("ё", "е"))


def match_rule(name):
    """(подгруппа, вид) для названия товара, или None — если правила нет или товар не трогаем."""
    normalized = " ".join((name or "").lower().replace("ё", "е").split())
    for pattern, subgroup, leaf in _COMPILED:
        if pattern.search(normalized):
            return (subgroup, leaf) if subgroup else None
    return None


def _category_lookup(category_model):
    lookup = {}
    categories = category_model.objects.select_related("parent__parent").annotate(n=Count("supplier_products"))
    for category in categories:
        parent = category.parent
        if parent is None:
            continue
        group = parent.parent
        rank = (_key(group.name if group else "") == _FOOD_ROOT_KEY, category.n, str(category.id))
        key = (_key(parent.name), _key(category.name))
        if key not in lookup or rank > lookup[key][0]:
            lookup[key] = (rank, category)
    return {key: value[1] for key, value in lookup.items()}


def assign_missing_categories(supplier_product_model, category_model, *, apply):
    """Проставить категорию товарам поставщиков без неё. Возвращает Counter
    {(подгруппа, вид): число} и список названий без подходящего правила."""
    lookup = _category_lookup(category_model)
    assigned, unmatched = Counter(), []
    to_update = []
    for item in supplier_product_model.objects.filter(category__isnull=True).only("id", "supplier_name"):
        hit = match_rule(item.supplier_name)
        category = lookup.get((_key(hit[0]), _key(hit[1]))) if hit else None
        if category is None:
            unmatched.append(item.supplier_name)
            continue
        assigned[hit] += 1
        item.category = category
        to_update.append(item)
    if apply and to_update:
        supplier_product_model.objects.bulk_update(to_update, ["category"], batch_size=500)
    return assigned, unmatched
