"""Есть ли в названии явное указание страны -- только такие строки имеет смысл отправлять в модель за страной
(замер 2026-10-01: страна нужна <5% строк, а 23% ответов модели по стране не опирались на текст)."""

import re

# Корни названий стран и их прилагательных; границу слова в конце не требуем (итальянск-ий/-ая/-ое).
# «корейка» (мясо) не должна срабатывать, поэтому корни «корея»/«корейск», а не «корей».
_COUNTRY_STEMS = (
    "росси|рф\\b|итали|италь|испан|франц|герман|китай|турц|турци|турец|бразил|аргентин|инди[яй]|египет|израил|"
    "польш|польск|беларус|белорус|украин|казахстан|груз|армен|азербайдж|эквадор|тайланд|таиланд|тайск|вьетнам|"
    "перу\\b|чили\\b|марокк|юар\\b|нидерланд|голланд|бельги|греци|греческ|серб|индонез|зеланд|узбек|швейцар|"
    "австри|дани[яи]|датск|финлянд|финск|норвег|мексик|сша\\b|парагва|уругва|колумб|кени[яи]|тунис|иран|корея|"
    "корейск|япони|японск|португал|венгр|болгар|румын|чехи|чешск|литв|латви|эстон|молдов|молдав|киргиз|монгол|"
    "тайван|шри.?ланк|кипр\\b|хорват|словен|словац|ирланд|англи|британ"
)
_COUNTRY_HINT_RE = re.compile(rf"(?<![а-яa-z])(?:{_COUNTRY_STEMS})", re.IGNORECASE)


def has_country_hint(name):
    return bool(_COUNTRY_HINT_RE.search(name or ""))
