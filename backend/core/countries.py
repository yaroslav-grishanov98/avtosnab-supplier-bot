COUNTRY_ALIASES = {name.casefold(): name for name in COUNTRY_NAMES}
for _country, _aliases in _EXTRA_COUNTRY_ALIASES.items():
    for _alias in _aliases:
        COUNTRY_ALIASES[_alias.casefold()] = _country
del _country, _aliases, _alias

# Длинные маркеры раньше коротких («страна происхождения» раньше «страна»).
_COUNTRY_MARKER_RE = re.compile(
    r"^(?:страна происхождения|страна|производство|пр-во|made in|product of|продукция)"
    r"(?:\s*[:\-–—]\s*|\s+)"
)
_WHITESPACE_RE = re.compile(r"\s+")


def normalize_country(text):
    """Название страны из COUNTRY_NAMES по тексту целиком или None.

    Допускает только сам текст страны (название, сокращение, английское имя)
    с необязательным маркером вроде «пр-во», «Страна:», «made in». Любой текст
    с запятой, слешем или лишними словами — не страна.
    """
    if not text:
        return None
    value = _WHITESPACE_RE.sub(" ", str(text).casefold()).strip()
    value = _COUNTRY_MARKER_RE.sub("", value, count=1).strip()
    if value not in COUNTRY_ALIASES and value.endswith("."):
        # «Россия.», «РФ.»: one trailing dot is punctuation, not part of the name («Рос.» is an alias of its own).
        value = value[:-1].strip()
    return COUNTRY_ALIASES.get(value)
