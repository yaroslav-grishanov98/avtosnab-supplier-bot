from django.db import IntegrityError, migrations, transaction


def _slugify(name):
    return name.lower().replace(" ", "-").replace(",", "")


def _get_or_create_by_slug(ProductCategory, *, name, parent, slug):
    # Top-level group slugs are a bare slugify(name) with no parent prefix, so
    # they can collide with a category that real supplier-import auto-creation
    # (_resolve_category_path) already created earlier under a name that isn't
    # a literal string match (different case/whitespace) but slugifies the
    # same. get_or_create's (name, parent) lookup misses that row, then the
    # insert hits the slug unique constraint. Look up by slug first — if a
    # node with this slug already exists, it's the same real-world category
    # regardless of exact name spelling, so reuse it instead of crashing.
    existing = ProductCategory.objects.filter(slug=slug).first()
    if existing is not None:
        return existing
    try:
        with transaction.atomic():
            return ProductCategory.objects.create(name=name, parent=parent, slug=slug, status="active")
    except IntegrityError:
        return ProductCategory.objects.get(slug=slug)


