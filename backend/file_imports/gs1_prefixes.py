"""Таблица GS1 Prefix -> страна (трёхзначные диапазоны), для подсказки страны по штрихкоду.

ВАЖНО: GS1 Prefix показывает, где зарегистрирован код (страна члена GS1), а не где товар
сделан: компания может производить в любой стране. Поэтому страна по префиксу — только
слабая подсказка, а не факт происхождения (так пишет и сам GS1 на странице источника).

Источник: https://www.gs1.org/standards/id-keys/company-prefix (таблица GS1 Prefix).
Дата получения: 2026-10-17. Сырой текст страницы: manifests/raw_sources.csv,
id `src_gs1_prefix_list_20261017` (gs1.org отдаёт 403 не-браузерным клиентам, PDF/CSV нет).
Файл сгенерирован скриптом из этого текста, а не набран по памяти.

Правила отображения:
- строки со списком через `&` разбиты на отдельные диапазоны (`450-459 & 490-499` -> Япония,
  `680-681 & 690-699` -> Китай); повторы одного диапазона схлопнуты;
- берутся только трёхзначные диапазоны: GTIN-8 и короткие префиксы (`0000000`,
  `0000001 - 0000099`, `00001 - 00009`, `0001 - 0009`, купоны `99`) не используются;
- пропущено всё, что не члены GS1: restricted circulation (020-029, 040-049, 200-299),
  `050-059` (GS1 US reserved), `950`-`952` (Global Office, demonstrations), `960-969`
  (GTIN-8), `977` (ISSN), `978-979` (ISBN), `980` (refund), `981-983` (купоны) и строки
  `Managed by GS1 Global Office for future MO` (610, 614, 623, 758, 894);
- члены GS1 сопоставлены значениям core.countries.COUNTRY_NAMES; член без соответствия
  валит генерацию, молча не пропускается. Спорные соответствия:
  `GS1 BIH` -> Босния и Герцеговина, `Emirates` -> ОАЭ, `Republica Dominicana` ->
  Доминиканская Республика, `Türkiye` -> Турция, `Brasil` -> Бразилия, `Kazakstan` ->
  Казахстан, `Czech` -> Чехия, `UK` -> Великобритания, `Association Greece` -> Греция,
  `Macedonia` -> Северная Македония, `Hong Kong, China` -> Гонконг, `Macau, China` ->
  Макао, `Chinese Taipei` -> Тайвань, `Kosovo` -> Косово, `El Salvador` -> Сальвадор;
- `GS1 Belgium & Luxembourg` (540-549) -> Бельгия: диапазон отображается в одно значение,
  люксембургские коды этим префиксом не отличить от бельгийских.

12-значный UPC-A имеет неявный ведущий ноль: у UPC 614141234561 префикс 061, а не 614;
поэтому США покрывает и 001-019, 030-039, 060-139.
Список игнорируемых префиксов (020-029, 040-049, 050-059, 200-299, 960-969, 977-979,
980-999) применяется в file_imports.barcode.gs1_country, а не здесь.
"""

